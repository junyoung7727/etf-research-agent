const {chromium}=require('../../edge/node_modules/@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1700,height:1080}});
 page.setDefaultTimeout(120000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const out='output/puppygraph-viewer-20261005';
 const ready=()=>page.waitForFunction(()=>document.querySelector('#graph').getAttribute('aria-busy')==='false');
 try{
  await page.goto('http://127.0.0.1:5186/puppygraph');
  await page.waitForSelector('.node');await ready();
  assert.equal(await page.locator('.view-modes button').count(),2);
  assert.equal(await page.locator('#relation,#onDate,#expand').count(),0);
  const allNodes=await page.locator('.node').count(),allEdges=await page.locator('.edge').count();
  assert(allNodes>20&&allEdges>20);
  assert.equal(await page.locator('.node circle.node-circle').count(),allNodes);
  assert((await page.locator('#notice').innerText()).includes('일부 연결 표시 중'));
  await page.screenshot({path:out+'/all-real-connections.png',fullPage:true});
  await page.locator('#query').fill('449450');await page.locator('#searchButton').click();await ready();
  await page.locator('.result').click();await ready();
  assert.equal(await page.locator('#oneMode').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.node[data-type="ETF"]').count(),1);
  assert(await page.locator('.node[data-type="ETFHolding"]').count()>0);
  assert(await page.locator('.node[data-type="DailyBar"]').count()>0);
  assert(await page.locator('.node[data-type="DailyNAV"]').count()>0);
  const holding=page.locator('.node[data-type="ETFHolding"]').first();
  await holding.focus();await holding.press('Enter');
  assert((await page.locator('#properties').innerText()).includes('securityName'));
  assert((await page.locator('#properties').innerText()).includes('displayTitle'));
  assert((await holding.locator('title').textContent()).includes('PLUS K방산'));
  const before=await page.locator('.edge').count();
  await page.locator('#more').click();await ready();
  const after=await page.locator('.edge').count();assert(after>before);
  const keys=await page.locator('.edge').evaluateAll(nodes=>nodes.map(n=>n.dataset.key));assert.equal(new Set(keys).size,keys.length);
  const root=page.locator('.node[data-type="ETF"]');
  const previous=await root.getAttribute('transform'),box=await root.locator('.node-circle').boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2+45,box.y+box.height/2+20,{steps:5});await page.mouse.up();
  assert.notEqual(await root.getAttribute('transform'),previous);
  await root.locator('.node-circle').click();assert((await page.locator('#properties').innerText()).includes('449450'));
  await page.screenshot({path:out+'/one-real-connections.png',fullPage:true});
  await page.route('**/api/puppygraph/connections?**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'연결 시험 오류'})}));
  await page.locator('#allMode').click();await ready();
  assert.equal(await page.locator('.edge').count(),after);assert.equal(await page.locator('#oneMode').getAttribute('aria-pressed'),'true');
  assert((await page.locator('#notice').innerText()).includes('연결 시험 오류'));
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:out+'/two-modes-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await page.unroute('**/api/puppygraph/connections?**');
  await page.setViewportSize({width:1700,height:1080});
  await page.goto('http://127.0.0.1:5186/view-design?object=ETFHolding');
  await page.waitForSelector('[data-column="display_title"]');
  assert((await page.locator('[data-column="display_title"]').innerText()).includes('ontology_view.etf_holding'));
  await page.screenshot({path:out+'/holding-view-titles.png',fullPage:true});
  fs.writeFileSync(out+'/two-modes-verification.json',JSON.stringify({passed:true,allNodes,allEdges,focusEdgesBefore:before,focusEdgesAfter:after,errors},null,2));
  console.log('Two modes live browser verification passed', {allNodes,allEdges,before,after});
 }catch(error){
  console.error('Dashboard status:',await page.locator('#notice').innerText().catch(()=>''),'Browser errors:',errors);
  await page.screenshot({path:out+'/browser-failure.png',fullPage:true}).catch(()=>{});
  throw error;
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
