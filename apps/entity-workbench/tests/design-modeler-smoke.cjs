const {chromium}=require('../../edge/node_modules/@playwright/test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1680,height:1120}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 try{
  await page.goto('http://127.0.0.1:5186/modeler');
  await page.waitForFunction(()=>document.querySelectorAll('[data-object]').length===23);
  for(const name of ['ReportedSupplyContract','ETFHoldingCollectionStatus']){
   assert.equal(await page.locator(`[data-object="${name}"]`).count(),0);
   assert.equal(await page.locator(`#objectJump option[value="${name}"]`).count(),0);
  }
  assert((await page.locator('#saveState').textContent()).includes('YAML 원본과 일치'));
  assert.equal(await page.locator('[data-object="EventParticipation"]').count(),0);
  await page.locator('#objectJump').selectOption('Company');
  assert.equal(await page.locator('#semanticContract').count(),0);
  assert((await page.locator('#objectMetadata').innerText()).includes('Primary key'));
  const companyType=JSON.parse(await page.locator('#definitionJson').textContent());
  assert.equal(companyType.titleProperty,'name');
  assert.equal(companyType.status,'experimental');
  assert.equal(companyType.semanticContract,undefined);
  const companyLinks=JSON.parse(await page.locator('#relationsJson').textContent());
  const disclosureLink=companyLinks.find(r=>r.type==='HasDisclosure');
  assert.equal(disclosureLink.inverse.apiName,'forCompany');
  assert.equal(companyLinks.filter(r=>r.from==='Disclosure'&&r.to==='Company').length,0);
  await page.locator('[data-property="id"] summary').click();
  const identity=await page.locator('[data-property="id"]').innerText();
  assert(identity.includes('NOT NULL')&&identity.includes('FK')&&identity.includes('actor_id + actor_type'));
  await page.locator('#previewSearch').fill('삼성전자');
  await page.locator('#previewButton').click();
  await page.waitForSelector('#objectJson');
  assert.equal(JSON.parse(await page.locator('#objectJson').textContent()).node.properties.name,'삼성전자');
  await page.screenshot({path:'output/entity-workbench/design-company-constraints.png',fullPage:true});
  await page.locator('#objectJump').selectOption('ETFHolding');
  await page.locator('#previewSearch').fill('');
  await page.locator('#previewButton').click();
  await page.waitForSelector('#objectJson');
  assert.equal(JSON.parse(JSON.parse(await page.locator('#objectJson').textContent()).node.id).length,3);
  await page.locator('#objectJump').selectOption('EventThread');
  assert(await page.locator('#previewButton').isDisabled());
  assert((await page.locator('#previewStats').textContent()).includes('수집되지 않았습니다'));
  await page.locator('[data-property="lastStateAt"] summary').click();
  assert((await page.locator('[data-property="lastStateAt"]').innerText()).includes('not necessarily a state change'));
  await page.locator('[data-property="currentStage"] summary').click();
  assert((await page.locator('[data-property="currentStage"]').innerText()).includes('매핑 수정 필요'));
  await page.locator('#objectJump').selectOption('NewsArticle');
  const relations=JSON.parse(await page.locator('#relationsJson').textContent());
  const reports=relations.find(r=>r.type==='DescribesEvent'&&r.from==='NewsArticle');
  assert.equal(reports.linkProperties,undefined);
  assert.deepEqual(Object.keys(reports.sourceMapping.evidenceFields),['extractionConfidence']);
  assert.equal(reports.sourceMapping.joins.length,3);
  await page.locator('#fitModel').click();
  await page.locator('[data-relation="Company_HasDisclosure_Disclosure"] .link-caption').click();
  assert((await page.locator('#linkDirections').innerText()).includes('ForCompany'));
  assert((await page.locator('#linkDirections').innerText()).includes('HasDisclosure'));
  await page.locator('#objectJump').selectOption('FinancialMetric');
  assert((await page.locator('[data-property="id"] summary').textContent()).includes('Primary key'));
  assert((await page.locator('[data-property="corpCode"] summary').textContent()).includes('원본 PK'));
  assert(!(await page.locator('[data-property="corpCode"] summary').textContent()).includes('Primary key'));
  assert.equal(await page.locator('[data-property="receivedAt"]').count(),1);
  assert.equal(await page.locator('[data-property="availabilityBasis"]').count(),1);
  await page.locator('#objectJump').selectOption('DailyBar');
  for(const field of ['openPrice','highPrice','lowPrice']){
   await page.locator(`[data-property="${field}"] summary`).click();
   const definition=await page.locator(`[data-property="${field}"]`).innerText();
   assert(definition.includes('원본 연결 대기'));
   assert(definition.includes('연결된 원본 없음'));
  }
  const daily=JSON.parse(await page.locator('#definitionJson').textContent());
  assert.equal(daily.propertyDefinitions.volume.dataType,'Long');
  assert.equal(daily.sourceMapping.properties.volume.column,'volume');
  await page.screenshot({path:'output/entity-workbench/design-daily-ohlcv.png',fullPage:true});
  await page.locator('#objectJump').selectOption('ReportedBusinessSegment');
  assert.equal(await page.locator('[data-property="isCurrent"]').count(),0);
  assert.equal(await page.locator('[data-property="isCurrentExtraction"]').count(),0);
  assert.equal(await page.locator('[data-property="lateDisclosure"]').count(),0);
  await page.locator('#objectJump').selectOption('SecurityIndustryClassification');
  for(const field of ['marketCap','listingMarket','isPrimaryShare'])assert.equal(await page.locator(`[data-property="${field}"]`).count(),0);
  await page.locator('#objectJump').selectOption('Organization');
  const participationLinks=JSON.parse(await page.locator('#relationsJson').textContent());
  const participation=participationLinks.find(r=>r.type==='ParticipatesIn'&&r.to==='SourceEvent');
  assert(participation);
  assert.deepEqual(Object.keys(participation.linkProperties).sort(),['mentionedName','roleCode']);
  assert.deepEqual(participation.sourceMapping.identity,['event_argument_id']);
  await page.locator('[data-relation="Organization_ParticipatesIn_SourceEvent"] .link-hit').dispatchEvent('click');
  assert.equal(await page.locator('[data-link-property="roleCode"]').count(),1);
  await page.locator('#objectJump').selectOption('FinancialReportSnapshot');
  assert.equal(await page.locator('[data-property="reportCoverage"]').count(),1);
  await page.locator('#objectJump').selectOption('MarketIndex');
  assert.equal(JSON.parse(await page.locator('#definitionJson').textContent()).titleProperty,'seriesName');
  await page.locator('#fitModel').click();
  await page.screenshot({path:'output/entity-workbench/design-24-types.png',fullPage:true});
  const model=await (await page.request.get('http://127.0.0.1:5186/api/model')).json();
  const status=await (await page.request.get('http://127.0.0.1:5186/api/status')).json();
  const stale=await page.request.post('http://127.0.0.1:5186/api/model/preview',{headers:{'X-Workbench-Token':status.token},data:{revision:model.revision-1,object_id:'Company'}});
  assert.equal(stale.status(),409);
  const write=await page.request.post('http://127.0.0.1:5186/api/model',{headers:{'X-Workbench-Token':status.token},data:{model:{objects:[],relations:[]},revision:model.revision}});
  assert.equal(write.status(),405);
  await page.setViewportSize({width:850,height:1100});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  assert.equal(model.model.relations.length,37);
  const result={revision:model.revision,types:model.model.objects.length,links:model.model.relations.length,yamlMatches:model.yaml_matches,checks:['Foundry-style metadata','single bidirectional link type','no interpretation-rule schema','source/model nullability','complete composite FK','company source preview','composite holding identity','uncaptured data distinct from zero rows','pending lifecycle and timestamp mappings','news extraction evidence kept in source mapping','financial availability basis','stale revision rejected','read-only writes rejected','narrow layout'],pageErrors:errors};
  fs.writeFileSync('output/entity-workbench/design-modeler-verification.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
